const grid=document.getElementById('menuGrid'),search=document.getElementById('menuSearch'),count=document.getElementById('itemCount'),empty=document.getElementById('menuEmpty');
let category='all';
function renderMenu(){const term=search.value.trim().toLowerCase();const filtered=menu.filter(item=>(category==='all'||item.category===category)&&(`${item.name} ${item.desc||''}`).toLowerCase().includes(term));grid.innerHTML=filtered.map((item,i)=>`<article class="menu-item" style="animation-delay:${Math.min(i*18,250)}ms"><div><h3>${item.name}</h3>${item.desc?`<p>${item.desc}</p>`:''}<span class="veg">● &nbsp;VEGETARIAN</span></div><span class="price">₹${item.price.toFixed(2)}</span></article>`).join('');count.textContent=`${filtered.length} ${filtered.length===1?'DISH':'DISHES'}`;empty.hidden=filtered.length!==0;}
document.querySelectorAll('.tab').forEach(btn=>btn.addEventListener('click',()=>{document.querySelector('.tab.active').classList.remove('active');btn.classList.add('active');category=btn.dataset.category;renderMenu()}));search.addEventListener('input',renderMenu);renderMenu();
document.getElementById('year').textContent=new Date().getFullYear();
